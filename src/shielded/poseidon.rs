//! Phase S1.2 — off-circuit **Poseidon1** reference hash over the Pallas base
//! field `Fp`.
//!
//! This is the field-element hash that the note commitment (S1.3), nullifier
//! derivation (S1.4), and incremental Merkle tree (S1.6) will be built on. It is
//! the *off-circuit reference* implementation; the in-circuit sponge (S2) must
//! share **byte-identical round constants + MDS** with this one so the two are
//! mutually verifiable.
//!
//! # Field
//!
//! The hash operates over **`pasta_curves::pasta::Base`** (`Fp`, the Pallas base
//! field), *not* the scalar field `Fq`. The Halo2 circuit is `Circuit<Fp>`, so
//! every field-element primitive (sponge, tree leaves, commitments) lives in
//! `Fp` — this corrects the plan's loose `Fr`.
//!
//! # S-box exponent: `x^7`, not `x^5`
//!
//! Poseidon's S-box is `x ↦ x^α`, which is a permutation of `Fp` only when
//! `gcd(α, p-1) = 1`. For the Pallas base field `p ≡ 1 (mod 5)`, so
//! `gcd(5, p-1) = 5` and **`x^5` is NOT a bijection** — an `x^5` S-box would
//! collapse the permutation. The smallest valid exponent is `3` (too weak for a
//! 255-bit field); `7` is the canonical fallback used by gnark / plonky and gives
//! a strong, invertible S-box. This implementation therefore uses **α = 7**.
//!
//! # Parameters (Grain-LFSR derived)
//!
//! The round constants and MDS matrix are generated by the canonical,
//! reproducible Grain-LFSR method (the Poseidon paper's algorithm, as used by
//! gnark / light-poseidon / plonky):
//!
//! * Grain LFSR taps `[0, 13, 23, 38, 51, 62]`, 80-bit seed encoding
//!   `(field_type=1, sbox=0, n=255, t=5, R_F=8, R_P=46, 30 ones)`, 160 warm-up
//!   clocks.
//! * State width **t = 5**, `R_F = 8` full rounds, `R_P = 46` partial rounds.
//! * Round constants: `(R_F + R_P) · t = 54 · 5 = 270` field elements, drawn in
//!   order from the Grain stream.
//! * **Cauchy** MDS: `M[i][j] = 1 / (xs[i] + ys[j])` over 2t distinct Grain-
//!   sampled elements (xs = first t, ys = last t), drawn by continuing the SAME
//!   Grain stream after the round constants.
//!
//! # Sponge convention
//!
//! Rate `r = t - 1 = 4`, capacity `c = 1`. Input is padded with **Pad\*10\***:
//! append a single `1`, then zeros to a multiple of `r`. Absorb `r` elements into
//! the first `r` lanes, permute. After the last permutation, **squeeze lane
//! `t-1`** (the capacity lane) → one `Fp` output. Pad\*10\* is length-sensitive:
//! `hash([a]) ≠ hash([a, 0])`, which guards against a length-blind hash.
//!
//! Poseidon deliberately does **not** implement the SHA-256 `HashProvider` trait
//! (`crypto.rs:645`): its I/O is `&[Fp]`, not `&[u8]`, so the field types are
//! incompatible.

use once_cell::sync::Lazy;

use ff::{Field, PrimeField};
use pasta_curves::pallas::Base as Fp;

/// State width `t`.
const T: usize = 5;
/// S-box exponent. `x^7` — required because `gcd(5, p-1) = 5` over Pallas `Fp`
/// (see module docs); `x^7` is a bijection.
const ALPHA_EXP: u64 = 7;
/// Total full rounds `R_F` (split as `R_F / 2` before and after the partial
/// rounds).
const R_F: usize = 8;
/// Partial rounds `R_P`.
const R_P: usize = 46;
/// Sponge rate `r = t - 1`.
const RATE: usize = T - 1;
/// Bit length of the Pallas base field prime `p`.
const N_BITS: usize = 255;

/// A round-constants table: one `[Fp; T]` per round, in round order.
type RcTable = [[Fp; T]; R_F + R_P];
/// The 5×5 Cauchy MDS matrix.
type MdsMatrix = [[Fp; T]; T];

/// Pre-computed Poseidon parameters: round constants then the Cauchy MDS matrix.
///
/// Generated once (lazily) from a single Grain-LFSR stream: the round constants
/// are drawn first, then the MDS generation **continues the same stream**.
static PARAMS: Lazy<Params> = Lazy::new(|| {
    let mut grain = Grain::new();
    let rc = round_constants(&mut grain);
    let mds = cauchy_mds(&mut grain);
    Params { rc, mds }
});

struct Params {
    rc: RcTable,
    mds: MdsMatrix,
}

/// The Grain-LFSR used to derive Poseidon round constants + MDS (index-pointer
/// form; reads the feedback taps relative to the current head `p`).
struct Grain {
    /// 80-bit shift register.
    s: [u8; 80],
    /// Read/write pointer (the current head position).
    p: usize,
}

impl Grain {
    fn new() -> Self {
        fn bits(val: u64, w: usize) -> Vec<u8> {
            (0..w).rev().map(|i| ((val >> i) & 1) as u8).collect()
        }
        // 80-bit seed: field_type(1)=1, sbox(0)=0, n=255, t=5, R_F=8, R_P=46, 30 ones.
        let mut s: Vec<u8> = Vec::with_capacity(80);
        s.extend_from_slice(&bits(1, 2)); // field_type: GF(p)
        s.extend_from_slice(&bits(0, 4)); // sbox index
        s.extend_from_slice(&bits(N_BITS as u64, 12)); // n
        s.extend_from_slice(&bits(T as u64, 12)); // t
        s.extend_from_slice(&bits(R_F as u64, 10)); // R_F
        s.extend_from_slice(&bits(R_P as u64, 10)); // R_P
        s.extend_from_slice(&[1u8; 30]); // ones
        assert_eq!(s.len(), 80, "Grain seed must be 80 bits");
        let s: [u8; 80] = s
            .try_into()
            .expect("80-bit Grain seed — the assertions above guarantee this");
        let mut g = Grain { s, p: 0 };
        // 160 warm-up clocks before any output.
        for _ in 0..160 {
            g.tick();
        }
        g
    }

    fn mix(&self, p: usize) -> u8 {
        let s = self.s;
        // Feedback taps relative to the current head `p`.
        s[(p + 0) % 80]
            ^ s[(p + 13) % 80]
            ^ s[(p + 23) % 80]
            ^ s[(p + 38) % 80]
            ^ s[(p + 51) % 80]
            ^ s[(p + 62) % 80]
    }

    /// Advance the register by one clock; return the feedback bit that is
    /// clocked into the head.
    fn tick(&mut self) -> u8 {
        let p = self.p;
        let nb = self.mix(p);
        self.s[p] = nb; // write feedback into the head, then shift.
        self.p = (p + 1) % 80;
        nb
    }

    /// Next keystream bit: clock twice, return the second bit iff the first is 1
    /// (otherwise retry).
    fn next_bit(&mut self) -> u8 {
        loop {
            let a = self.tick();
            let b = self.tick();
            if a == 1 {
                return b;
            }
        }
    }

    /// Sample one field element: draw `N_BITS` bits and form the integer
    /// `v = int(bits, 2)` (first Grain bit is the most significant, at absolute
    /// bit `N_BITS - 1 = 254`), then take its canonical representative via
    /// `ff::PrimeField::from_repr`, rejecting (`>= p`) by redrawing — identical to
    /// the reference `int(bits, 2) < p` rejection.
    ///
    /// `from_repr` expects the **little-endian** repr, so each Grain bit `i` is
    /// placed at absolute bit position `254 - i` (not `255 - i`): placing it one
    /// bit higher would shift the whole value left by one and produce a
    /// different constant stream.
    fn field_element(&mut self) -> Fp {
        loop {
            let mut repr = [0u8; 32];
            for i in 0..N_BITS {
                let ap = (N_BITS - 1) - i; // 254 down to 0
                repr[ap / 8] |= (self.next_bit() as u8) << (ap % 8);
            }
            let opt = Fp::from_repr(repr);
            let mut v = Fp::zero();
            if bool::from(opt.is_some()) {
                // < p, so this is the canonical representative: extract it.
                opt.map(|x| {
                    v = x;
                });
                return v;
            }
            // else value >= p: reject and redraw.
        }
    }
}

/// Draw `(R_F + R_P) · t` field elements from the Grain stream and lay them out
/// as one `[Fp; T]` per round.
fn round_constants(grain: &mut Grain) -> RcTable {
    let n = (R_F + R_P) * T;
    let mut raw = Vec::with_capacity(n);
    for _ in 0..n {
        raw.push(grain.field_element());
    }
    let mut table = [[Fp::zero(); T]; R_F + R_P];
    for (row, chunk) in table.iter_mut().zip(raw.chunks(T)) {
        row.copy_from_slice(chunk);
    }
    table
}

/// Build the Cauchy MDS matrix `M[i][j] = 1 / (xs[i] + ys[j])` by continuing the
/// same Grain stream after the round constants.
fn cauchy_mds(grain: &mut Grain) -> MdsMatrix {
    loop {
        // Sample 2t distinct field elements.
        let mut rand = Vec::with_capacity(2 * T);
        while rand.len() < 2 * T {
            let v = grain.field_element();
            if !rand.contains(&v) {
                rand.push(v);
            }
        }
        let xs = &rand[..T];
        let ys = &rand[T..];
        // Reject if any xs[i] + ys[j] ≡ 0 (would make the inverse undefined).
        let mut valid = true;
        for (i, x) in xs.iter().enumerate() {
            for (j, y) in ys.iter().enumerate() {
                if bool::from((*x + *y) == Fp::zero()) {
                    valid = false;
                    break;
                }
            }
            if !valid {
                break;
            }
        }
        if !valid {
            continue;
        }
        let mut mds = [[Fp::zero(); T]; T];
        for (i, row) in mds.iter_mut().enumerate() {
            for (j, cell) in row.iter_mut().enumerate() {
                let x = xs[i] + ys[j];
                // x is nonzero here (checked above), so its inverse is defined.
                let mut inv_val = Fp::zero();
                x.invert().map(|v| {
                    inv_val = v;
                });
                *cell = inv_val;
            }
        }
        return mds;
    }
}

/// S-box `x ↦ x^7`. `x^7 = x^4 · x^2 · x`; two squarings + two multiplies.
fn sbox(x: Fp) -> Fp {
    let x2 = x.square();
    let x4 = x2.square();
    x4 * x2 * x
}

/// Multiply the state by the MDS matrix: `out[i] = Σ_j mds[i][j] · state[j]`.
fn matvec(mds: &MdsMatrix, state: &[Fp; T]) -> [Fp; T] {
    let mut out = [Fp::zero(); T];
    for (i, out_cell) in out.iter_mut().enumerate() {
        let mut acc = Fp::zero();
        for j in 0..T {
            acc += mds[i][j] * state[j];
        }
        *out_cell = acc;
    }
    out
}

/// Poseidon1 permutation: `R_F/2` full rounds → `R_P` partial rounds → `R_F/2`
/// full rounds. Every round adds its round constants, applies the S-box (all
/// lanes for full rounds, only lane 0 for partial rounds), then multiplies by
/// the MDS matrix.
fn permute(state: &mut [Fp; T], params: &Params) {
    let rc = &params.rc;
    let mds = &params.mds;
    let half = R_F / 2;
    let mut idx = 0;

    // Initial full rounds.
    for _ in 0..half {
        for k in 0..T {
            state[k] += rc[idx][k];
        }
        for k in 0..T {
            state[k] = sbox(state[k]);
        }
        *state = matvec(mds, state);
        idx += 1;
    }
    // Partial rounds.
    for _ in 0..R_P {
        for k in 0..T {
            state[k] += rc[idx][k];
        }
        state[0] = sbox(state[0]);
        *state = matvec(mds, state);
        idx += 1;
    }
    // Terminal full rounds.
    for _ in 0..half {
        for k in 0..T {
            state[k] += rc[idx][k];
        }
        for k in 0..T {
            state[k] = sbox(state[k]);
        }
        *state = matvec(mds, state);
        idx += 1;
    }
}

/// Absorb the input with Pad\*10\* and return the post-permutation state — the
/// last permutation's full 5-lane output. Exposed for diffusion testing.
fn sponge_perm_state(inputs: &[Fp]) -> [Fp; T] {
    let params = &PARAMS;
    let mut state = [Fp::zero(); T];
    let mut padded = Vec::with_capacity(inputs.len() + 2);
    padded.extend_from_slice(inputs);
    padded.push(Fp::one()); // Pad*: terminate with a 1
    while padded.len() % RATE != 0 {
        padded.push(Fp::zero());
    }
    for chunk in padded.chunks(RATE) {
        for i in 0..chunk.len() {
            state[i] += chunk[i];
        }
        permute(&mut state, params);
    }
    state
}

/// Absorb the input and **squeeze** the capacity lane (`t - 1`): one `Fp` output.
fn sponge_hash(inputs: &[Fp]) -> Fp {
    sponge_perm_state(inputs)[T - 1]
}

/// Trait for a Poseidon hash over the Pasta base field.
///
/// Deliberately NOT the SHA-256 `HashProvider` trait (`crypto.rs:645`): its I/O
/// is `&[Fp]`, not `&[u8]`, so the field types are incompatible.
pub trait PoseidonHasher {
    fn hash(&self, inputs: &[Fp]) -> Fp;
}

/// Zero-sized Poseidon hash provider over the Pallas base field. `new()` ==
/// `default()` — the implementation is a stateless free function.
#[derive(Debug, Clone, Copy, Default)]
pub struct PoseidonHashProvider;

impl PoseidonHasher for PoseidonHashProvider {
    fn hash(&self, inputs: &[Fp]) -> Fp {
        sponge_hash(inputs)
    }
}

/// Off-circuit Poseidon1 reference: `&[Fp] → Fp` over the Pallas base field.
///
/// See the module docs for the parameter set, S-box exponent, and sponge
/// convention. The in-circuit sponge (S2) must share these exact constants.
pub fn poseidon_hash(inputs: &[Fp]) -> Fp {
    PoseidonHashProvider.hash(inputs)
}

