    /// Deterministic: identical inputs → identical output across repeated calls.
    #[test]
    fn poseidon_is_deterministic() {
        let inputs = vec![Fp::from(42), Fp::from(1), Fp::from(7), Fp::zero()];
        let a = poseidon_hash(&inputs);
        let b = poseidon_hash(&inputs);
        let c = poseidon_hash(&inputs);
        assert_eq!(a, b);
        assert_eq!(b, c);
    }

    /// Discriminator (tamper): flipping one input element changes the output.
    #[test]
    fn poseidon_tamper_changes_output() {
        let inputs = vec![Fp::from(1), Fp::from(2), Fp::from(3)];
        let mut tampered = inputs.clone();
        tampered[1] += Fp::one(); // flip one input element
        assert_ne!(
            poseidon_hash(&inputs),
            poseidon_hash(&tampered),
            "mutating one input must change the hash"
        );
    }

    /// Length sensitivity: Pad10* makes `hash([a]) ≠ hash([a, 0])`. A
    /// length-blind hash (naive zero-padding) would collide these.
    #[test]
    fn poseidon_length_sensitive() {
        let a = Fp::from(12345);
        assert_ne!(
            poseidon_hash(&[a]),
            poseidon_hash(&[a, Fp::zero()]),
            "Pad10* must make differing-length inputs hash differently"
        );
        assert_ne!(
            poseidon_hash(&[a]),
            poseidon_hash(&[a, Fp::zero(), Fp::zero()]),
        );
        assert_ne!(
            poseidon_hash(&[a, Fp::zero()]),
            poseidon_hash(&[a, Fp::zero(), Fp::zero()]),
        );
    }

    /// Diffusion: perturbing a single input lane must propagate to *several*
    /// output lanes of the post-permutation state. A one-round or under-rounded
    /// permutation would leave other lanes untouched.
    #[test]
    fn poseidon_diffuses_across_lanes() {
        let inputs = vec![Fp::from(1), Fp::from(2), Fp::from(3), Fp::from(4)];
        let mut tampered = inputs.clone();
        tampered[0] += Fp::one();

        let state0 = sponge_perm_state(&inputs);
        let state1 = sponge_perm_state(&tampered);

        // At least 3 of the 5 output lanes must differ (a real permutation
        // diffuses; a weak one would not).
        let diff_count = state0.iter().zip(state1.iter()).filter(|(a, b)| a != b).count();
        assert!(
            diff_count >= 3,
            "expected diffusion into >=3 lanes, only {diff_count} changed"
        );
        // And of course the squeezed capacity lane differs too.
        assert_ne!(state0[T - 1], state1[T - 1]);
    }

    /// Discriminator proof: the KAT depends on a *non-trivial* round count and
    /// exponent. Temporarily dropping a partial round (or flipping the S-box to a
